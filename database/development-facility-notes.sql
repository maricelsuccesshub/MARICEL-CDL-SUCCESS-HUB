-- Development-only migration for private member facility notes.
-- Apply to the development Supabase project, never production without review.

create table if not exists public.facility_notes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  facility_name text not null check (char_length(facility_name) between 1 and 150),
  facility_address text check (char_length(facility_address) <= 300),
  entrance_lat numeric check (entrance_lat between -90 and 90),
  entrance_lon numeric check (entrance_lon between -180 and 180),
  guard_lat numeric check (guard_lat between -90 and 90),
  guard_lon numeric check (guard_lon between -180 and 180),
  entrance_notes text check (char_length(entrance_notes) <= 1500),
  guard_notes text check (char_length(guard_notes) <= 1500),
  approach_notes text check (char_length(approach_notes) <= 1500)
);

create index if not exists facility_notes_owner_created
  on public.facility_notes(user_id, created_at desc);

alter table public.facility_notes enable row level security;

revoke all on public.facility_notes from anon, authenticated;
grant select, insert on public.facility_notes to authenticated;
grant usage, select on sequence public.facility_notes_id_seq to authenticated;

drop policy if exists facility_notes_select_own on public.facility_notes;
create policy facility_notes_select_own
  on public.facility_notes for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists facility_notes_insert_own on public.facility_notes;
create policy facility_notes_insert_own
  on public.facility_notes for insert
  to authenticated
  with check ((select auth.uid()) = user_id);
