create table public.safe_havens (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  submitted_by uuid not null default auth.uid() references auth.users(id),
  location_name text check (char_length(location_name) <= 200),
  city text check (char_length(city) <= 200),
  state text check (char_length(state) <= 50),
  parking_spots bigint check (parking_spots >= 0),
  overnight_allowed boolean,
  restrooms boolean,
  showers boolean,
  diesel boolean,
  food_nearby text check (char_length(food_nearby) <= 1000),
  notes text check (char_length(notes) <= 4000)
);

create index safe_havens_submitter_created
  on public.safe_havens(submitted_by, created_at desc);

alter table public.safe_havens enable row level security;
revoke all on public.safe_havens from anon, authenticated;
grant select, insert on public.safe_havens to authenticated;
grant usage on sequence public.safe_havens_id_seq to authenticated;

create policy safe_havens_read_members
  on public.safe_havens for select
  to authenticated
  using (true);

create policy safe_havens_insert_own
  on public.safe_havens for insert
  to authenticated
  with check ((select auth.uid()) = submitted_by);
