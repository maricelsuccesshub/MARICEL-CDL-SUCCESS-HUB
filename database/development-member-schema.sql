
create table public.member_profiles (
 user_id uuid primary key references auth.users(id),
 display_name text check (char_length(display_name)<=100),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table public.member_progress (
 id bigint generated by default as identity primary key,
 user_id uuid not null default auth.uid() references auth.users(id),
 progress_date date not null default current_date,
 backing_practice text check(char_length(backing_practice)<=4000),
 went_well text check(char_length(went_well)<=4000),
 needs_improvement text check(char_length(needs_improvement)<=4000),
 confidence text check(char_length(confidence)<=100),
 created_at timestamptz not null default now()
);
create index member_progress_owner_date on public.member_progress(user_id,created_at desc);
alter table public.member_profiles enable row level security;
alter table public.member_progress enable row level security;
revoke all on public.member_profiles,public.member_progress from anon,authenticated;
grant select,insert,update on public.member_profiles to authenticated;
grant select,insert on public.member_progress to authenticated;
grant usage on sequence public.member_progress_id_seq to authenticated;
create policy profiles_read_own on public.member_profiles for select to authenticated using ((select auth.uid())=user_id);
create policy profiles_insert_own on public.member_profiles for insert to authenticated with check ((select auth.uid())=user_id);
create policy profiles_update_own on public.member_profiles for update to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
create policy progress_read_own on public.member_progress for select to authenticated using ((select auth.uid())=user_id);
create policy progress_insert_own on public.member_progress for insert to authenticated with check ((select auth.uid())=user_id);
